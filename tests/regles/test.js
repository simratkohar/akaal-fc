const { initializeTestEnvironment, assertSucceeds, assertFails } = require('@firebase/rules-unit-testing');
const fs = require('fs');
let ok = 0, ko = 0;
async function t(nom, p) { try { await p; ok++; console.log('✓', nom); } catch (e) { ko++; console.log('✗', nom, e.message.slice(0, 150)); } }
(async () => {
  const env = await initializeTestEnvironment({ projectId: 'akaal-test', firestore: { rules: fs.readFileSync(__dirname + '/../../firestore.rules', 'utf8').replaceAll('TON_EMAIL@gmail.com', 'cap@test.fr'), host: '127.0.0.1', port: 8089 } });
  const now = Date.now();
  await env.withSecurityRulesDisabled(async c => {
    const db = c.firestore();
    await db.doc('joueurs/p2').set({ nom: 'Karan', numero: 5, role: 'joueur', email: 'j@test.fr' });
    await db.doc('joueurs/p3').set({ nom: 'Arjun', numero: 8, role: 'joueur', email: 'a@test.fr', uid: 'uA' });
    await db.doc('acces/uA').set({ joueur: 'p3', role: 'joueur' });
    await db.doc('matchs/m1').set({ joue: false, limite: now + 864e5, ontJoue: [] });
    await db.doc('matchs/m2').set({ joue: false, limite: now - 1000, ontJoue: [] });
    await db.doc('matchs/m3').set({ joue: true, votesFin: now + 864e5, ontJoue: ['p2', 'p3'] });
    await db.doc('matchs/m4').set({ joue: true, votesFin: now + 864e5, ontJoue: ['p3'] });
    await db.doc('matchs/m5').set({ joue: true, votesFin: now - 1000, ontJoue: ['p2', 'p3'] });
    await db.doc('paiements/c1').set({ libelle: 'x', joueurs: { p2: false } });
  });
  const anon = env.unauthenticatedContext().firestore();
  const cap = env.authenticatedContext('uCap', { email: 'cap@test.fr', email_verified: true }).firestore();
  const pirate = env.authenticatedContext('uX', { email: 'pirate@test.fr', email_verified: true }).firestore();
  const j = env.authenticatedContext('uJ', { email: 'j@test.fr', email_verified: true }).firestore();

  await t('anonyme ne lit pas les joueurs', assertFails(anon.doc('joueurs/p2').get()));
  await t('visiteur lit les matchs', assertSucceeds(anon.doc('matchs/m1').get()));
  await t('visiteur lit la liste des matchs', assertSucceeds(anon.collection('matchs').get()));
  await t('visiteur ne lit pas les paiements', assertFails(anon.doc('paiements/c1').get()));
  await t('visiteur ne lit pas les votes', assertFails(anon.collection('votes').get()));
  await t('visiteur ne lit pas les accès', assertFails(anon.doc('acces/uA').get()));
  await t('visiteur ne lit pas la liste des joueurs (e-mails)', assertFails(anon.collection('joueurs').get()));
  await t('visiteur ne modifie pas un match', assertFails(anon.doc('matchs/m1').update({ joue: true })));
  await t('pirate ne lit pas les paiements', assertFails(pirate.doc('paiements/c1').get()));
  await t('pirate ne peut pas créer l’équipe', assertFails(pirate.doc('equipe/config').set({ nom: 'x' })));
  await t('pirate ne peut pas se lier à la fiche de Karan', assertFails(pirate.doc('acces/uX').set({ joueur: 'p2', role: 'joueur' })));
  await t('capitaine (fondateur) crée sa fiche', assertSucceeds(cap.doc('joueurs/p1').set({ nom: 'Simratpal', role: 'capitaine', email: 'cap@test.fr', uid: 'uCap' })));
  await t('capitaine crée son accès', assertSucceeds(cap.doc('acces/uCap').set({ joueur: 'p1', role: 'capitaine' })));
  await t('capitaine crée la config', assertSucceeds(cap.doc('equipe/config').set({ nom: 'Akaal FC' })));
  await t('non lié : cherche sa fiche par e-mail', assertSucceeds(j.collection('joueurs').where('email', '==', 'j@test.fr').get()));
  await t('non lié : ne lit pas toute la liste', assertFails(j.collection('joueurs').get()));
  await t('joueur ne peut pas se lier en capitaine', assertFails(j.doc('acces/uJ').set({ joueur: 'p2', role: 'capitaine' })));
  await t('joueur se lie à sa fiche', assertSucceeds(j.doc('acces/uJ').set({ joueur: 'p2', role: 'joueur' })));
  await t('joueur enregistre son uid', assertSucceeds(j.doc('joueurs/p2').update({ uid: 'uJ', photoGoogle: null })));
  await t('joueur ne peut pas se promouvoir', assertFails(j.doc('acces/uJ').update({ role: 'capitaine' })));
  await t('joueur change sa photo', assertSucceeds(j.doc('joueurs/p2').update({ photo: 'data:image/jpeg;base64,xxx' })));
  await t('photo trop lourde refusée', assertFails(j.doc('joueurs/p2').update({ photo: 'x'.repeat(400000) })));
  await t('joueur ne change pas son numéro', assertFails(j.doc('joueurs/p2').update({ numero: 10 })));
  await t('joueur ne change pas la photo d’un autre', assertFails(j.doc('joueurs/p3').update({ photo: 'data:x' })));
  await t('capitaine change la photo d’un joueur', assertSucceeds(cap.doc('joueurs/p3').update({ photo: 'data:x' })));
  await t('joueur lit les matchs', assertSucceeds(j.doc('matchs/m1').get()));
  await t('joueur ne crée pas de match', assertFails(j.doc('matchs/mX').set({ joue: false })));
  await t('joueur ne modifie pas un score', assertFails(j.doc('matchs/m3').update({ scoreNous: 9 })));
  await t('joueur ne saisit pas de but', assertFails(j.doc('buts/b1').set({ match: 'm3', buteur: 'p2' })));
  await t('joueur répond présent', assertSucceeds(j.doc('presences/m1_p2').set({ match: 'm1', joueur: 'p2', reponse: 'present' })));
  await t('joueur ne répond pas pour un autre', assertFails(j.doc('presences/m1_p3').set({ match: 'm1', joueur: 'p3', reponse: 'absent' })));
  await t('joueur bloqué après la date limite', assertFails(j.doc('presences/m2_p2').set({ match: 'm2', joueur: 'p2', reponse: 'present' })));
  await t('capitaine change une réponse après la limite', assertSucceeds(cap.doc('presences/m2_p2').set({ match: 'm2', joueur: 'p2', reponse: 'absent' })));
  await t('joueur vote', assertSucceeds(j.doc('votes/m3_p2').set({ match: 'm3', joueur: 'p2', hommeDuMatch: 'p3' })));
  await t('joueur ne met pas de notes', assertFails(j.doc('votes/m3_p2').set({ match: 'm3', joueur: 'p2', hommeDuMatch: 'p3', notes: { p3: 8 } })));
  await t('joueur ne note pas dans le match', assertFails(j.doc('matchs/m3').update({ notes: { p2: 10 } })));
  await t('capitaine note tout le monde, lui compris', assertSucceeds(cap.doc('matchs/m3').update({ notes: { p1: 6.5, p2: 8 } })));
  await t('joueur ne vote pas pour lui-même', assertFails(j.doc('votes/m3_p2').set({ match: 'm3', joueur: 'p2', hommeDuMatch: 'p2', notes: {} })));
  await t('pas de vote si pas joué', assertFails(j.doc('votes/m4_p2').set({ match: 'm4', joueur: 'p2', hommeDuMatch: 'p3', notes: {} })));
  await t('pas de vote après clôture', assertFails(j.doc('votes/m5_p2').set({ match: 'm5', joueur: 'p2', hommeDuMatch: 'p3', notes: {} })));
  await t('joueur ne vote pas au nom d’un autre', assertFails(j.doc('votes/m3_p3').set({ match: 'm3', joueur: 'p3', hommeDuMatch: 'p2', notes: {} })));
  await t('joueur voit les paiements', assertSucceeds(j.doc('paiements/c1').get()));
  await t('joueur ne se marque pas payé', assertFails(j.doc('paiements/c1').update({ joueurs: { p2: true } })));
  await t('capitaine coche payé', assertSucceeds(cap.doc('paiements/c1').update({ joueurs: { p2: true } })));
  await t('capitaine crée un profil public', assertSucceeds(cap.doc('profils/p2').set({ nom: 'Karan', numero: 5, photo: null })));
  await t('visiteur lit les profils', assertSucceeds(anon.collection('profils').get()));
  await t('visiteur ne modifie pas un profil', assertFails(anon.doc('profils/p2').update({ nom: 'X' })));
  await t('joueur change la photo de son profil public', assertSucceeds(j.doc('profils/p2').update({ photo: 'data:y' })));
  await t('joueur ne change pas le nom de son profil', assertFails(j.doc('profils/p2').update({ nom: 'Messi' })));
  await t('joueur ne touche pas au profil d’un autre', assertFails(j.doc('profils/p1').set({ nom: 'x' })));
  await t('capitaine nomme un 2e capitaine', assertSucceeds(cap.doc('acces/uA').update({ role: 'capitaine' })));
  const a = env.authenticatedContext('uA', { email: 'a@test.fr', email_verified: true }).firestore();
  await t('le 2e capitaine peut créer un match', assertSucceeds(a.doc('matchs/m9').set({ joue: false })));
  console.log(`\n${ok} réussis, ${ko} échoués`);
  await env.cleanup(); process.exit(ko ? 1 : 0);
})();
